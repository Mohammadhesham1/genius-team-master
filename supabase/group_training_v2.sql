-- ----------------------------------------------------------------------------
-- Adds a dedicated persistent-state table (group_progress) and reseeds
-- group_round_questions with 5 general-knowledge rounds (subject_id = NULL,
-- since these rounds mix topics and aren't tied to a single subject).
-- Safe to re-run.
-- ============================================================================

-- ── group_progress: one row per (round, question), the single source of truth
-- for that question's attempts + final result. Deleting rows IS the reset.
create table if not exists public.group_progress (
  round_no   int not null,
  position   int not null,
  attempts   jsonb not null default '[]'::jsonb,
  final      text check (final in ('correct','wrong')),
  updated_at timestamptz not null default now(),
  primary key (round_no, position)
);

alter table public.group_progress enable row level security;

drop policy if exists "anon_read_group_progress" on public.group_progress;
create policy "anon_read_group_progress" on public.group_progress for select using (true);
drop policy if exists "anon_write_group_progress" on public.group_progress;
create policy "anon_write_group_progress" on public.group_progress for insert with check (true);
drop policy if exists "anon_update_group_progress" on public.group_progress;
create policy "anon_update_group_progress" on public.group_progress for update using (true) with check (true);
drop policy if exists "anon_delete_group_progress" on public.group_progress;
create policy "anon_delete_group_progress" on public.group_progress for delete using (true);

